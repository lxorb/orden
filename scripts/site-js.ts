import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { resolve } from 'node:path'
import { sourceHash } from './site-sources.ts'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = new URL('../', import.meta.url)
const ENTRY = fileURLToPath(new URL('apps/desktop/src/site/site.ts', ROOT))
const TARGET = fileURLToPath(new URL('services/sync/src/sync-server-blog/src/script.ts', ROOT))

async function bundle(): Promise<string> {
  const vite = (await import(
    pathToFileURL(
      createRequire(fileURLToPath(new URL('apps/desktop/package.json', ROOT))).resolve('vite'),
    ).href
  )) as typeof import('vite')

  const out = await vite.build({
    root: fileURLToPath(ROOT),
    logLevel: 'warn',
    configFile: false,
    build: {
      write: false,
      target: 'es2022',
      minify: 'esbuild',
      lib: { entry: ENTRY, formats: ['iife'], name: 'nibSite', fileName: () => 'site.js' },
    },
  })

  const chunks = Array.isArray(out) ? out : [out]
  for (const one of chunks) {
    if (!('output' in one)) continue
    for (const file of one.output) {
      if (file.type === 'chunk' && file.isEntry) return file.code
    }
  }

  throw new Error('the site script bundled to nothing')
}

const THEME_JS =
  "try{var t=localStorage.getItem('orden:site-theme')||localStorage.getItem('nib:site-theme');if(t)document.documentElement.setAttribute('data-theme',t)}catch(e){}"

export async function siteScript(): Promise<string> {
  const code = await bundle()
  const path = `/s/${createHash('sha256').update(code).digest('hex').slice(0, 16)}.js`

  return `/* Generated by scripts/site-js.ts from apps/desktop/src/site/site.ts.
 * Do not edit: run \`pnpm blog:js\`. site-script.test.ts fails if it is stale.
 *
 * What a published page does in a browser, bundled with the app's own graph
 * layout and painter inside it. Served from the site's own domain at a path that
 * is its own hash - never from a CDN, for the reason the KaTeX faces are not
 * either. A page that carries none of the things it drives does not link it. */

export const SITE_JS = ${JSON.stringify(code)}

/** The one inline script a page carries, and the hash the policy names it by. */
export const THEME_JS = ${JSON.stringify(THEME_JS)}

export const THEME_JS_HASH = ${JSON.stringify(
    `sha256-${createHash('sha256').update(THEME_JS).digest('base64')}`,
  )}

export const SITE_JS_PATH = ${JSON.stringify(path)}

/** What the sources added up to when this was built; see scripts/site-js.ts. */
export const SITE_JS_SOURCES = ${JSON.stringify(sourceHash())}
`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const written = await siteScript()
  writeFileSync(TARGET, written)
  console.log(`wrote ${TARGET} (${(written.length / 1024).toFixed(1)}kB)`)
}
