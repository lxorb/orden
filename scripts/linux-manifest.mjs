/** Linux's manifest, written from the app's own.
 *
 *  Linux runs Orden on CEF (Chromium) through `tauri-runtime-cef`, which exists for
 *  Tauri 3 only, while macOS, Windows and the phones stay on Tauri 2. Tauri 2 and 3 both
 *  declare `links = "Tauri"`, which Cargo allows once per dependency graph whatever the
 *  target, so the two cannot share a manifest: `apps/desktop/src-tauri/linux/Cargo.toml`
 *  is the same package, compiled from the same files, with the Tauri family moved to the
 *  pins in the app manifest's `[package.metadata.cef]` and the `cef` feature on.
 *
 *  A list kept by hand beside the real one is one crate short the day somebody adds a
 *  crate, so the whole of that file is this script's output, and `--check` fails when it
 *  is not what this would write (check.yml runs it).
 *
 *  A Linux build puts it in place of the app's manifest, with its own lock file, in a
 *  checkout of its own: scripts/linux-cef.sh.
 *
 *      node scripts/linux-manifest.mjs           # write it
 *      node scripts/linux-manifest.mjs --check   # fail if it is stale
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const HEADER = `# GENERATED by scripts/linux-manifest.mjs from ../Cargo.toml. Do not edit by hand:
# change ../Cargo.toml (its [package.metadata.cef] for the pins) and run the script.
#
# Orden on Linux: the app's own package against Tauri 3 and tauri-runtime-cef, with the
# \`cef\` feature on, so the interface and every web tab run on CEF (Chromium). Built in
# place of ../Cargo.toml, with ./Cargo.lock beside it; see scripts/linux-cef.sh.
`

/** The pins `[package.metadata.cef]` names, by crate. */
function pinsOf(app) {
  const table = /\n\[package\.metadata\.cef\]\n([\s\S]*?)\n\[/.exec(app)
  if (!table?.[1]) throw new Error('Cargo.toml names no [package.metadata.cef]')
  const pins = new Map()
  for (const line of table[1].split('\n')) {
    const found = /^([a-z0-9-]+) = "([^"]+)"$/.exec(line.trim())
    if (found?.[1] && found[2]) pins.set(found[1], found[2])
  }
  return pins
}

const listed = (features) => features.map((one) => `"${one}"`).join(', ')

/** The features a `tauri = { ... features = [...] }` line asks for. */
const featuresOf = (line) =>
  [...(/features = \[([^\]]*)\]/.exec(line)?.[1] ?? '').matchAll(/"([^"]+)"/g)].map(
    (one) => one[1] ?? '',
  )

/** One dependency line of the app's tables, as Linux's build needs it. */
function moved(line, pins, table) {
  const pin = (name) => {
    const value = pins.get(name)
    if (!value) throw new Error(`[package.metadata.cef] has no pin for ${name}`)
    return value
  }
  const name = /^([A-Za-z0-9_-]+) = /.exec(line)?.[1]
  if (!name) return [line]

  if (name === 'tauri-build') return [`tauri-build = "=${pin('tauri-build')}"`]
  if (name === 'tauri-utils') return [`tauri-utils = "=${pin('tauri-utils')}"`]
  if (name === 'tauri') {
    const features = featuresOf(line)
    // The app's own `tauri`, the one every build has: Tauri 3 with what the app asks for,
    // the interface embedded as a release does, and beside it the engine, Tauri's
    // runtime interface at the release the engine was built against, and the crate
    // the library reaches Chromium's own objects through.
    if (features.includes('protocol-asset')) {
      return [
        `tauri = { version = "=${pin('tauri')}", features = [${listed([...features, 'custom-protocol'])}] }`,
        `tauri-runtime-cef = { version = "=${pin('tauri-runtime-cef')}", features = ["unstable"] }`,
        `tauri-runtime = "=${pin('tauri-runtime')}"`,
        `cef = { version = "=${pin('cef')}", default-features = false }`,
      ]
    }
    // A platform's own: the developer tools, which Tauri 3 takes from the runtime, and
    // anything else as Tauri 2 took it.
    const kept = features.filter((one) => one !== 'devtools')
    return [
      ...(features.includes('devtools')
        ? [
            `tauri-runtime-cef = { version = "=${pin('tauri-runtime-cef')}", features = ["devtools"] }`,
          ]
        : []),
      ...(kept.length > 0
        ? [`tauri = { version = "=${pin('tauri')}", features = [${listed(kept)}] }`]
        : []),
    ]
  }
  if (name === 'tauri-plugin-dialog' && table === LINUX_DESKTOP) {
    // The file dialogs through the desktop portal, not GTK 3: CEF's runtime is GTK 4, and
    // GTK 3 and 4 in one process is a crash at start (GTK 3's `gtk_init_check` answers
    // GTK 4's call). The portal is what a Wayland desktop and Flatpak use anyway.
    return [
      `tauri-plugin-dialog = { version = "=${pin(name)}", default-features = false, features = ["xdg-portal"] }`,
    ]
  }
  if (name.startsWith('tauri-plugin-')) {
    const rest = /^[a-z-]+ = \{ version = "[^"]*"(.*)$/.exec(line)?.[1]
    return [
      rest === undefined
        ? `${name} = "=${pin(name)}"`
        : `${name} = { version = "=${pin(name)}"${rest}`,
    ]
  }
  if (name.startsWith('tauri')) {
    throw new Error(`the app depends on ${line}, which Linux's build has no pin for`)
  }
  return [line]
}

/** The desktops' shared table, the one whose dialog plugin is Linux's. */
const LINUX_DESKTOP =
  '[target.\'cfg(any(target_os = "windows", target_os = "linux", target_os = "macos"))\'.dependencies]'

/** Tables Linux's build leaves out: the BSDs' WebKitGTK. */
const DROPPED = new Set([
  '[target.\'cfg(any(target_os = "dragonfly", target_os = "freebsd", target_os = "netbsd", target_os = "openbsd"))\'.dependencies]',
])

/** Linux's manifest from the app's manifest `app`. */
export function linuxManifest(app) {
  app = app.replace(/\r\n/g, '\n')
  const pins = pinsOf(app)
  const lines = app.split('\n')

  const out = []
  let table = ''
  let skipping = false
  // A value that spans lines (`features = [` ... `]`) is copied whole.
  let open = false
  for (const raw of lines) {
    const line = raw.trimEnd()
    if (open) {
      if (!skipping) out.push(line)
      if (/^\s*\]\s*\}?\s*$/.test(line) || /^\]/.test(line)) open = false
      continue
    }
    if (line.trim() === '' || line.trimStart().startsWith('#')) continue
    if (line.startsWith('[')) {
      table = line
      skipping = DROPPED.has(line) || line === '[package.metadata.cef]'
      if (!skipping) out.push('', line)
      continue
    }
    if (skipping) {
      if (/\[\s*$/.test(line)) open = true
      continue
    }
    if (table === '[features]' && line.startsWith('cef = ')) {
      out.push('default = ["cef"]', line)
      continue
    }
    if (/\[\s*$/.test(line)) {
      open = true
      out.push(line)
      continue
    }
    const inDependencies = /dependencies\]$/.test(table)
    out.push(...(inDependencies ? moved(line, pins, table) : [line]))
  }
  return `${HEADER}${out.join('\n')}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const at = (path) => fileURLToPath(new URL(path, import.meta.url))
  const target = at('../apps/desktop/src-tauri/linux/Cargo.toml')
  const made = linuxManifest(readFileSync(at('../apps/desktop/src-tauri/Cargo.toml'), 'utf8'))
  if (process.argv.includes('--check')) {
    let was = ''
    try {
      was = readFileSync(target, 'utf8')
    } catch {
      // Not written yet, which is stale too.
    }
    if (was !== made) {
      console.error(
        'apps/desktop/src-tauri/linux/Cargo.toml is not what scripts/linux-manifest.mjs writes from Cargo.toml; run it',
      )
      process.exit(1)
    }
  } else {
    writeFileSync(target, made)
  }
}
