const TYPED = new Set(['text', 'search', 'email', 'url', 'tel', 'password', 'number'])
export function shapeOf(cursor: string, element: Element | null): Shape {
  if (cursor === 'pointer') return 'hand'
  if (cursor === 'text' || cursor === 'vertical-text') return 'text'
  if (cursor !== 'auto' || !element) return 'arrow'
  if (element instanceof HTMLTextAreaElement) return 'text'
  if (element instanceof HTMLInputElement) return TYPED.has(element.type) ? 'text' : 'arrow'
  return element instanceof HTMLElement && element.isContentEditable ? 'text' : 'arrow'
}
