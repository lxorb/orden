import { describe, expect, test } from 'vitest'
import { backtracksWildly } from './pattern-cost'

describe('a pattern that could backtrack without end', () => {
  test.each([
    '(a+)+b',
    '(a*)*$',
    '(a|a)+$',
    '(a|ab)*c',
    '(\\w+\\s?)+$',
    '((a+))+$',
    '(?:a+)+$',
    '(a[ab]+)+$',
    '(\\s*\\w+)*$',
    '(a|aa)+$',
    '(a|a)'.repeat(30),
    '('.repeat(5000) + 'a' + ')'.repeat(5000),
    '(.*) (.*) (.*)QQQ',
    '\\w+.*\\w+.*QQQ',
    '.*\\b.*\\b.*QQQ',
    '.* .* .* .*QQQ',
    '.*e.*o.*e.*o.*X',
    '[^X]*e[^X]*e[^X]*X',
    '[^X]*e[^X]*X',
    '[\\s\\S]*e[\\s\\S]*X',
    '(.*,){5}x',
    '.*,.*,.*!',
    '.*@\\w+.*!',
    '(.*) (.*)$',
    '.*e.*X',
    '(.*) (.*)\\d+',
    '.* .*\\d+',
    '.*.*\\d+',
    '.*\\s*.*\\d+',
    '[\\s\\S]*eX',
    '[\\s\\S]*bar',
    '[^/]+\\.md',
    '[^"]*"',
    'e[\\s\\S]*X',
    '(.*)\\s+(.*)\\d+',
    '(\\w+ ?){12}\\.',
    '(\\w+\\s?){11}$',
    '(.* ){11}Q',
    '(?:.*\\s){11}Q',
    '(\\s?\\w+){12}\\.',
    '(\\w+ ?){12,}\\.',
    '(#\\w*\\w*)+X',
    '(\\w+\\s?)+$',
    '(\\w+\\s+)+X',
    '(\\w+,\\s*)+X',
    '(?:(?!- ).*\\n)+(?=- )',
    '(?:(?!#).*\\n)+(?=#)',
    '(?:(?!\\n).*\\n)+(?=\\n)',
    '(?:(?!TODO)\\S+\\s)+(?=TODO)',
    '(?:(?<!x).*\\n)+(?<=x)',
    '(?<=\\[\\[[^\\]]*)\\w+',
    '(?<=\\*\\*[^*]*)\\w+',
    '(?<!\\[[^\\]]*)\\w+',
    '(?<=^---[\\s\\S]*)\\w+',
    '(?<=\\[\\[[^\\]]*)the',
    '(?<=- [\\s\\S]*)the',
    '(?:.*\\n)*(?:#\\w+\\s)*#\\w+',
    '(?:.*\\n)*(?:\\d+,)*\\d+',
    '(?:.*\\n)*(?:- .*\\n)*- .*',
    '[\\s\\S]*(?:bar)*bar',
    '[^#]*(?:#\\w+ )*#\\w+',
    '.*(?:\\w+\\s)+\\w+',
    '.*?(?:\\w+, ){1,30}\\w+',
    '(\\S+\\s)+TODO',
    '(\\S+\\s)*X',
    '(\\S+\\s)+:',
    '(?:\\s\\S+)+X',
    '(?:\\s\\S+){2,}\\w+X',
    '(?:.*\\n){0,8}.*TODO',
    '(?:.*\\n){0,10}TODO',
    '(?:.*\\n)*TODO',
  ])('/%s/ is told apart before it runs', (source) => {
    expect(backtracksWildly(source)).toBe(true)
  })

  test.each([
    'foo',
    'w[a-z]+d',
    '.*x',
    '^(foo|bar)+$',
    '\\d{4}-\\d{2}-\\d{2}',
    '\\b(\\w+) \\1\\b',
    '(?<x>a)\\k<x>',
    '[(a+)+]',
    '\\(a+\\)+',
    '^[a-z]+(-[a-z]+)*$',
    '^[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+$',
    '^(\\w+\\/)+',
    '^#(\\w+\\/)*\\w+$',
    '^(foo|far)+$',
    '(\\d+,)*\\d+',
    'foo.*bar.*baz.*qux',
    '\\w+@\\w+\\.\\w+',
    '\\[\\[.*\\]\\]',
    'TODO.*@\\w+.*!',
    '(\\w+) (\\w+)$',
    '\\(([^)]*)\\)',
    '-[^-]*-',
    '^\\s*(\\w+)\\s*:\\s*(.*)$',
    'foo[\\s\\S]*bar',
    '"[^"]*"',
    '[^/\\s]+\\.md',
    '\\s+-\\s+',
    '\\[\\[([^\\]|]+)(\\|[^\\]]+)?\\]\\]',
    '\\d+\\s*(kg|lb)',
    '[.!?]\\s+[a-z]',
    '(\\w+)\\s+\\1',
    '\\s+$',
    '\\s*:\\s*',
    '\\w+\\s*\\(',
    '\\b(a|an|the)\\s+\\1\\b',
    '\\s+(and|or)\\s+',
    '[A-Z][a-z]+\\s+[A-Z][a-z]+',
    '\\d{4}-\\d{2}-\\d{2}\\s+\\d{2}:\\d{2}',
    '^- \\[ \\] .*#\\w+.*$',
    '(#\\w+\\s*)+',
    '\\w+(,\\s*\\w+)*',
    '(?:\\[\\[[^\\]]+\\]\\]\\s*)+',
    '(\\d+[,.]\\s*)+',
    '(\\w+\\s+)+',
    '[a-f0-9]{32}',
    '(\\S+ )+TODO',
    '(?:>\\s.*\\n)+>',
    '(?:\\| [^|]* )+\\|',
    '(?:#\\w+\\s)+#\\w+',
    '([A-Z][a-z]+\\s)+[A-Z][a-z]+',
    '(?:Mr|Ms|Dr)\\.\\s(?:[A-Z][a-z]+\\s)+[A-Z]',
    '(?:\\w+\\.\\s)+\\w+',
    '(?:\\w+-\\s)+\\w+',
    '(?:\\w+\\s)+(\\w+)',
    '((?:\\w+,\\s*)+)(\\w+)',
    '(?:#\\w+\\s)+#(\\w+)',
    '([A-Z][a-z]+\\s)+([A-Z][a-z]+)',
    '(?:\\w+,\\s*)+(?:\\w+)',
    '(?:,[^,]*){11}',
    '(?:\\|[^|]*){11}',
    '(?:;[^;]*){12,20}',
    '(?:#[^#]*){11,}',
    '(?:\\|[^|\\n]*){11}\\|',
    '\\d{12}',
    '.*\\n.*TODO',
  ])('/%s/ may run', (source) => {
    expect(backtracksWildly(source)).toBe(false)
  })
})
